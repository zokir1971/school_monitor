def task_review_message(value, language):
    if isinstance(value, str):
        if value in TASK_REVIEW_ERRORS:
            return translate(value, language)
        for prefix, source in TASK_REVIEW_DETAIL_ERRORS.items():
            if value.startswith(prefix):
                return translate(source, language).format(items=value[len(prefix):])
        if value.startswith('Недопустимый статус задачи ID='):
            return translate(N_('Недопустимый статус выбранной задачи.'), language)
    return translate(N_('Не удалось сохранить рассмотрение. Проверьте выбранные задачи и данные протокола.'), language)
